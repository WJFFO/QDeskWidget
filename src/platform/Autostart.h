// -----------------------------------------------------------------------------
// Autostart —— 开机自启（Windows 当前用户启动项）的薄封装。
//
// 关键约定：
//  - 注册表 HKCU\Software\Microsoft\Windows\CurrentVersion\Run 是**唯一真值来源**，
//    settings.json 里不再存一份。多存一份的后果是：用户在「任务管理器 → 启动」里
//    关掉之后，设置面板仍会显示「已开启」，两边骗人。
//  - 只写 HKCU：不需要管理员权限，也不往 HKLM / 计划任务里塞东西，卸载就是删一个值。
//  - 便携形态的代价：程序文件夹被移动后启动项还指着旧路径，所以每次启动都调一次
//    syncIfEnabled() 顺手校正；未开启时它只是一次注册表读取，成本可忽略。
// -----------------------------------------------------------------------------
#pragma once

#include <QString>

namespace Autostart
{

/**
 * 当前平台是否支持开机自启（目前只有 Windows 有实现）。
 * @return Windows 恒为 true；其它平台 false，设置面板据此把开关置灰。
 */
bool isSupported();

/**
 * 是否已登记开机自启。
 * @return 启动项里存在本程序的值即为 true。注意它只判断「值存在」，
 *         不校验里面的路径是否还指向当前的 exe —— 路径校正交给 syncIfEnabled()。
 */
bool isEnabled();

/**
 * 打开 / 关闭开机自启。立即写注册表并 sync() 落盘。
 * @param on true = 写入启动项；false = 删除启动项（本来就没有也算成功）
 * @return 是否真的达到目标状态。失败时调用方应把界面上的勾恢复原样，
 *         不能假装成功——否则用户下次开机会发现没生效。
 */
bool setEnabled(bool on);

/**
 * 自愈：已开启但启动项里的路径不是当前 exe 时，重写成当前路径。
 * 便携版被移动 / 改名后靠它把启动项拉回来；未开启时什么都不做。
 * 正常启动流程调一次即可，不需要失败重试（下次启动还会再校正）。
 */
void syncIfEnabled();

/**
 * 当前 exe 应写进启动项的完整命令行（已按需加引号，路径带空格也能正确启动）。
 * 只做字符串拼装，不碰注册表；供 setEnabled() 内部使用，也让自检能打印出来核对。
 */
QString commandLine();

} // namespace Autostart
