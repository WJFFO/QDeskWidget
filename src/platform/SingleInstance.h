// -----------------------------------------------------------------------------
// SingleInstance —— 「同一时刻只允许一个进程」的硬保证（命名互斥体）。
//
// 为什么不用命名管道当锁：命名管道是「服务端自己 listen」，探测超时会被误判成
// 「没有实例在跑」（杀软扫描、系统卡顿时 waitForConnected 很容易超时），
// 而互斥体由内核维护，进程一死就自动回收，不存在残留锁文件的问题。
//
// 分工：本模块只回答「我是唯一实例吗」；把已有实例的窗口叫出来仍走命名管道（App.cpp）。
// 约定：acquire() 全进程只调一次，成功后独占权保持到进程退出，不需要显式 release。
// -----------------------------------------------------------------------------
#pragma once

#include <QString>

namespace SingleInstance
{

/**
 * 尝试取得本机（当前登录会话内）的独占权。
 * @param key 互斥体名，不含命名空间前缀（内部会加 "Local\"）
 * @return true  = 本进程是唯一实例，独占权一直持有到进程结束；
 *         false = 已有实例在运行，或系统连句柄都不给（此时宁可不开也不开两个）。
 */
bool acquire(const QString &key);

} // namespace SingleInstance
